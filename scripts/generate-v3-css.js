import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/**
 * 生成 v3 模板的样式常量。
 *
 * 为什么要把第三方 CSS 先存成 .ts 常量而不是运行时读文件：
 * 插件必须产出「单文件、完全离线」的 HTML，esbuild 打包时需要把样式文本
 * 直接内联进 main.js，因此沿用 katex-constants 的做法。
 *
 * markdown-editor.css 有两处不能原样带进导出文件：
 * 1. @font-face 指向站点的 /assets/*.woff2，离线必然 404；
 * 2. 从第一个 .katex 开始的 18KB 全是 KaTeX 样式，与 katex-constants 重复。
 * 所以这里直接截断到 .katex 之前，再清掉残余的 @font-face，
 * 只保留 .markdown-preview 滚动条、wiki-link、tag、mark 这些预览区规则。
 */
console.log('Generating v3 CSS constants...');

const themeCssPath = path.join(__dirname, '..', 'styles', 'v3', 'theme-switcher.css');
const editorCssPath = path.join(__dirname, '..', 'styles', 'v3', 'markdown-editor.css');

function readCss(filePath, label) {
	try {
		const css = fs.readFileSync(filePath, 'utf-8');
		console.log(`Read ${label}, length: ${css.length}`);
		return css;
	} catch (error) {
		console.error(`Error reading ${label} (${filePath}):`, error);
		process.exit(1);
	}
}

const themeCss = readCss(themeCssPath, 'theme-switcher.css');
const editorCss = readCss(editorCssPath, 'markdown-editor.css');

const katexStart = editorCss.indexOf('.katex');
if (katexStart < 0) {
	// 结构变了就说明上游资源不是预期的那份，宁可构建失败也不要产出坏文件
	console.error('Error: no .katex block found in markdown-editor.css, layout may have changed.');
	process.exit(1);
}

const editorCssPreview = editorCss
	.slice(0, katexStart)
	.replace(/@font-face[^}]+}/g, '');

console.log(`Kept ${editorCssPreview.length} chars of preview CSS (dropped ${editorCss.length - katexStart} chars of KaTeX)`);

for (const [label, css] of [['theme-switcher.css', themeCss], ['markdown-editor.css', editorCssPreview]]) {
	if (/url\(/.test(css)) {
		console.error(`Error: external url() reference remains in ${label}, aborting.`);
		process.exit(1);
	}
	if (/@font-face/.test(css)) {
		console.error(`Error: @font-face remains in ${label}, aborting.`);
		process.exit(1);
	}
}

if (!editorCssPreview.includes('.markdown-preview') || !editorCssPreview.includes('mark{')) {
	console.error('Error: expected preview rules (.markdown-preview / mark) are missing, aborting.');
	process.exit(1);
}

const output = `// Auto-generated file - do not edit
// Generated by scripts/generate-v3-css.js

export const V3_THEME_CSS = ${JSON.stringify(themeCss)};

export const V3_PREVIEW_CSS = ${JSON.stringify(editorCssPreview)};
`;

const outputPath = path.join(__dirname, '..', 'template-v3-css.ts');
fs.writeFileSync(outputPath, output, 'utf-8');

console.log('Generated template-v3-css.ts');
